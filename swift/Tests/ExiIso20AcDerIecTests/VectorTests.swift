import XCTest
@testable import ExiIso20AcDerIec

/// The Iso15118_20.AC_DER_IEC corpus — the one place in this project where "the vectors pass" means two
/// different things, so the test keeps the halves apart.
///
/// cbexigen does not generate the ISO 15118-20 Amendment 1 DER schemas, so for any message that
/// uses a DER member **no reference encoder exists**. What does exist: six of the plain-AC
/// messages encode identically under the DER grammar — measured, not assumed — and those carry
/// cbV2G's own bytes. The rest shift, because `DER_` sorts before `Dynamic_`/`Scheduled_` and
/// pushes their event codes along; those vectors are the C# back end's output.
///
/// So:
///
/// * the `cbV2G@…` vectors are real wire-conformance evidence;
/// * the `C#` ones are a **cross-language agreement check between two ports of
///   one grammar, plus a pin against drift** — passing them says the Swift and C# emitters read the
///   schema the same way, and nothing about what a conforming peer would accept.
///
/// The split is asserted rather than assumed, so the six anchored vectors cannot quietly be
/// replaced by self-generated bytes — the same guard `AcDerCorpusTests` provides on the C# side.
final class ExiIso20AcDerIecVectorTests: XCTestCase {

    private static let oraclePrefix = "cbV2G@"

    private struct Vector {
        let name: String
        let source: String
        let bytes: [UInt8]
        var fromOracle: Bool { source.hasPrefix(oraclePrefix) }
    }

    private static func repositoryRoot() throws -> URL {
        var dir = URL(fileURLWithPath: #filePath)
        for _ in 0..<12 {
            dir.deleteLastPathComponent()
            if FileManager.default.fileExists(atPath:
                dir.appendingPathComponent("EVSimulatorApp.slnx").path) { return dir }
        }
        throw XCTSkip("repository root not found from \(#filePath)")
    }

    private static func loadVectors() throws -> [Vector] {
        let url = try repositoryRoot().appendingPathComponent(
            "libs/WWCP_ISO15118/WWCP_ISO15118_EXI_Tests/Vectors/Iso15118_20.AC_DER_IEC.vectors.json")
        let json = try JSONSerialization.jsonObject(with: Data(contentsOf: url)) as? [String: Any]
        guard let raw = json?["vectors"] as? [[String: Any]] else {
            throw XCTSkip("vector file has no 'vectors' array: \(url.path)")
        }
        return raw.compactMap { v in
            guard let n = v["name"] as? String,
                  let s = v["source"] as? String,
                  let h = v["expectedHex"] as? String else { return nil }
            return Vector(name: n, source: s,
                          bytes: h.split(whereSeparator: { $0 == " " || $0 == "\n" })
                                  .compactMap { UInt8($0, radix: 16) })
        }
    }

    private static func hex(_ b: [UInt8]) -> String {
        b.map { String(format: "%02x", $0) }.joined(separator: " ")
    }

    private func reencode(_ m: Any) -> [UInt8]? {
        switch m {
        case let m as AC_ChargeParameterDiscoveryReq: return AcDerIecCodec.encode(m)
        case let m as AC_ChargeParameterDiscoveryRes: return AcDerIecCodec.encode(m)
        case let m as AC_ChargeLoopReq: return AcDerIecCodec.encode(m)
        case let m as AC_ChargeLoopRes: return AcDerIecCodec.encode(m)
        case let m as AC_CPDReqEnergyTransferMode: return AcDerIecCodec.encode(m)
        case let m as AC_CPDResEnergyTransferMode: return AcDerIecCodec.encode(m)
        default: return nil
        }
    }

    private func check(_ vectors: [Vector]) -> [String] {
        var failures: [String] = []
        for v in vectors {
            do {
                let decoded = try AcDerIecCodec.decodeAny(v.bytes)
                guard let actual = reencode(decoded) else {
                    failures.append("\(v.name): no encode overload for \(type(of: decoded))")
                    continue
                }
                if actual != v.bytes {
                    failures.append("\(v.name):\n  expected \(Self.hex(v.bytes))\n  actual   \(Self.hex(actual))")
                }
            } catch {
                failures.append("\(v.name): \(error)")
            }
        }
        return failures
    }

    /// Guards the provenance split itself. If the anchored six ever became self-generated, every
    /// other assertion here would still pass while the corpus quietly stopped being an oracle.
    func testTheCorpusKeepsItsAnchoredVectors() throws {
        let vectors = try Self.loadVectors()
        // 18 since 2026-08-08: `6ab05b8` added the two CurveDataPoint vectors for the minOccurs=2
        // particle nothing had ever populated — self-generated but cross-checked against EXIficient,
        // so the anchored six below are unchanged and still the only cbV2G bytes here.
        XCTAssertEqual(vectors.count, 18)
        XCTAssertEqual(vectors.filter(\.fromOracle).count, 6,
                       "the vectors carrying cbV2G's own bytes are the only wire-conformance evidence here")
    }

    /// Real wire conformance: these six are cbV2G's output for messages that encode identically
    /// under the DER grammar.
    func testTheAnchoredVectorsMatchTheReferenceEncoder() throws {
        let failures = check(try Self.loadVectors().filter(\.fromOracle))
        XCTAssertTrue(failures.isEmpty, "anchored vectors differ:\n" + failures.joined(separator: "\n"))
    }

    /// Cross-language agreement and a drift pin — *not* evidence of wire conformance, because
    /// these bytes are our own C# back end's output rather than a reference encoder's.
    func testTheSelfGeneratedVectorsAgreeWithTheCSharpBackEnd() throws {
        let failures = check(try Self.loadVectors().filter { !$0.fromOracle })
        XCTAssertTrue(failures.isEmpty,
                      "Swift and C# disagree on bytes no reference encoder can arbitrate:\n" +
                      failures.joined(separator: "\n"))
    }
}
