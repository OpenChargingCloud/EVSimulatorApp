#if canImport(CryptoKit)
import CryptoKit
import Foundation

/// Verifying a station's meter-signed reading — the vehicle's half of `SigMeterReading` (-2) and
/// `MeterSignature` (-20).
///
/// ## What this is for
///
/// Those are standard fields, `maxLength 64`, which is exactly one raw ECDSA P-256 `r‖s` pair. They
/// exist so the **meter** — not the SECC, not the CPO backend — can sign what it measured and hand
/// it to the vehicle, and they are almost never populated in the field. A phone that displays and
/// verifies one would be novel on its own, and it is the first leg of the three-way comparison in
/// `docs/CONCEPT.md` §4.3: the EV's own model against the *meter-signed* reading against OCPP
/// MeterValues.
///
/// ## The payload is a convention, not a standard
///
/// ISO 15118 defines the field and says nothing about what the signature covers, so the layout below
/// is this project's own (the C# `MeterSigningPayload` is the reference). A conforming peer would
/// have to be told it. That is also why `V2GMeteringTests` checks against a **corpus generated by
/// the C# side** rather than against itself: three implementations of one layout, each tested
/// against its own output, would agree perfectly and could all be wrong together.
///
/// ```
/// "V2G-METER-1\0"      12 bytes, domain separator
/// protocol              1 byte   2 or 20
/// sessionId             8 bytes
/// meterIdLength         1 byte
/// meterId               n bytes  UTF-8
/// reading               8 bytes  big-endian, Wh
/// timestamp             8 bytes  big-endian, unix seconds; 0 when absent
/// ```
///
/// The domain separator stops a signature over the same numbers elsewhere being replayed in as a
/// meter reading; the session id makes a reading provably *yours* rather than merely genuine; and
/// the length prefix stops meter `"A1"` reading 23 and meter `"A"` reading 123 producing the same
/// octets.
public enum MeterSignature {

    /// The wire length of the signature field: r and s, 32 bytes each.
    public static let signatureLength = 64

    public enum Error: Swift.Error, Equatable {
        /// Not 2 or 20 — the two protocols sign different payloads, so a reading cannot cross over.
        case unsupportedProtocol(Int)
        /// The layout gives the meter id a single length byte.
        case meterIdTooLong(Int)
    }

    /// Builds the octets the signature covers.
    ///
    /// Exposed rather than kept private because it is the thing to compare when a signature does not
    /// verify: agreeing on the crypto and disagreeing on the payload is the failure mode, and it is
    /// invisible from a boolean.
    public static func payload(protocol proto: Int,
                               sessionId: [UInt8],
                               meterId: String,
                               reading: UInt64,
                               timestamp: Int64?) throws -> [UInt8] {
        guard proto == 2 || proto == 20 else { throw Error.unsupportedProtocol(proto) }

        let id = Array(meterId.utf8)
        guard id.count <= 255 else { throw Error.meterIdTooLong(id.count) }

        var out: [UInt8] = []
        out.reserveCapacity(12 + 1 + sessionId.count + 1 + id.count + 16)

        out.append(contentsOf: Array("V2G-METER-1".utf8))
        out.append(0)
        out.append(UInt8(proto))
        out.append(contentsOf: sessionId)
        out.append(UInt8(id.count))
        out.append(contentsOf: id)
        out.append(contentsOf: bigEndian(reading))
        // Absent encodes as zero rather than being omitted, so the payload's length never depends on
        // which optional fields are present.
        out.append(contentsOf: bigEndian(UInt64(bitPattern: timestamp ?? 0)))

        return out
    }

    /// Verifies a reading a station sent.
    ///
    /// A signature of the wrong length is refused before CryptoKit sees it — that covers the DER
    /// form, which would not fit the 64-byte field anyway but is what a JCA- or OpenSSL-minded
    /// implementation produces by default.
    public static func verify(_ signature: [UInt8],
                              protocol proto: Int,
                              sessionId: [UInt8],
                              meterId: String,
                              reading: UInt64,
                              timestamp: Int64?,
                              publicKey: P256.Signing.PublicKey) throws -> Bool {
        guard signature.count == signatureLength,
              let parsed = try? P256.Signing.ECDSASignature(rawRepresentation: Data(signature))
        else { return false }

        let message = try payload(protocol: proto, sessionId: sessionId, meterId: meterId,
                                  reading: reading, timestamp: timestamp)
        return publicKey.isValidSignature(parsed, for: Data(message))
    }

    private static func bigEndian(_ value: UInt64) -> [UInt8] {
        (0..<8).reversed().map { UInt8((value >> ($0 * 8)) & 0xFF) }
    }
}
#endif
