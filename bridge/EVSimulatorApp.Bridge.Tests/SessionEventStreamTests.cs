using System.Text.Json;
using System.Text.Json.Nodes;
using EVSimulatorApp.Bridge;
using NUnit.Framework;

namespace EVSimulatorApp.Bridge.Tests;

/// <summary>
/// The bridge's event stream, and the one property nothing else in this repository checks.
/// </summary>
/// <remarks>
/// <para>
/// B1 asks the stream to carry every message "as JSON-LD <em>and</em> raw EXI". Each half is checked
/// elsewhere — the codecs against cbV2G's bytes, the JSON-LD against the document corpus — and
/// <b>nothing checks that the two halves of one event describe the same message</b>. An event whose
/// JSON-LD came from a different frame than its <c>exi</c> would pass every existing test in four
/// languages, and would be exactly the kind of thing an inspector cannot see: it shows you the JSON
/// and tells you the bytes are right there.
/// </para>
/// <para>
/// So <see cref="TheTwoHalvesOfAnEventAreTheSameMessage"/> decodes the event's own frame and compares
/// the result with the event's own JSON. That is the whole reason the raw frame is in the stream: it
/// makes the claim self-checkable by anyone holding it, including the WebView.
/// </para>
/// </remarks>
[TestFixture]
public class SessionEventStreamTests
{

    private const string CorpusFile = "Bridge.events.json";

    private static readonly JsonSerializerOptions Pretty = new() { WriteIndented = true };


    private static string RepositoryRoot
    {
        get
        {
            var directory = new DirectoryInfo(TestContext.CurrentContext.TestDirectory);
            while (directory is not null && !File.Exists(Path.Combine(directory.FullName, "EVSimulatorApp.slnx")))
                directory = directory.Parent;

            return directory?.FullName ?? throw new DirectoryNotFoundException("repository root not found");
        }
    }

    /// <summary>
    /// The session trace corpus, in <c>vectors/</c> here. It used to live in the conformance repository
    /// above and be read as <c>../../ISO15118ConformanceTests.Simulation/Vectors</c>; that path outlived
    /// the move on 2026-08-17 because the sweep searched every extension the ports use and not
    /// <c>*.cs</c>. What made it survive unnoticed is the <c>Assert.Ignore</c> below: a missing corpus
    /// reads as "nothing to do here" rather than as a failure, so this suite went on reporting success
    /// over a directory that no longer existed.
    /// </summary>
    private static string TraceDirectory =>
        Path.Combine(RepositoryRoot, "vectors");

    private static string CorpusPath =>
        Path.Combine(RepositoryRoot, "bridge/EVSimulatorApp.Bridge.Tests/Vectors", CorpusFile);


    /// <summary>Every recorded session, as the event stream it produces.</summary>
    private static JsonObject Produce()
    {

        // Not Assert.Ignore: vectors/ is committed beside this suite, so its absence is a broken working
        // tree rather than a checkout that lacks its parent — and an ignore here once hid a stale path
        // for as long as it took someone to run the regenerator by hand.
        Assert.That(Directory.Exists(TraceDirectory), Is.True,
                    $"the session trace corpus is missing at {TraceDirectory}. It is committed; "
                  + "`git checkout -- vectors` restores it.");

        var sessions = new JsonObject();

        foreach (var path in Directory.GetFiles(TraceDirectory, "Session.*.trace.json").OrderBy(p => p))
        {
            var trace  = JsonNode.Parse(File.ReadAllText(path))!;
            var stream = new SessionEventStream(new SteppingClock().Read);

            var events = new JsonArray();
            foreach (var evt in stream.Replay(trace))
                events.Add(SessionEventStream.ToJSON(evt));

            sessions[trace["name"]!.GetValue<string>()] = events;
        }

        return new JsonObject {
            ["note"]     = "Generated by SessionEventStreamTests.RegenerateTheCorpus. Every recorded "
                         + "session as the bridge's event stream: what a WebView inspector receives, "
                         + "with each message carried twice — as JSON-LD and as the raw V2GTP frame.",
            ["sessions"] = sessions,
        };
    }


    [Test, Explicit("Rewrites the checked-in event corpus. Run deliberately, and read the diff.")]
    public void RegenerateTheCorpus()
    {
        Directory.CreateDirectory(Path.GetDirectoryName(CorpusPath)!);
        File.WriteAllText(CorpusPath, Produce().ToJsonString(Pretty));

        TestContext.Out.WriteLine($"-> {CorpusPath}");
    }


    [Test]
    public void EveryEventIsUnchanged()
    {

        Assert.That(File.Exists(CorpusPath), Is.True, $"the event corpus is missing at {CorpusPath}");

        var expected = JsonNode.Parse(File.ReadAllText(CorpusPath))!["sessions"]!.AsObject();
        var actual   = Produce()["sessions"]!.AsObject();

        foreach (var (name, events) in expected)
        {
            Assert.That(actual.ContainsKey(name), Is.True, $"{name} is no longer produced");
            Assert.That(actual[name]!.ToJsonString(Pretty), Is.EqualTo(events!.ToJsonString(Pretty)), name);
        }
    }


    /// <summary>
    /// Within one event, the JSON-LD and the raw EXI are the same message.
    /// </summary>
    /// <remarks>
    /// Checked against the <b>checked-in</b> corpus rather than against a freshly produced stream,
    /// so it is a statement about what a consumer receives rather than about what this code happens
    /// to do in one run.
    /// </remarks>
    [Test]
    public void TheTwoHalvesOfAnEventAreTheSameMessage()
    {

        var sessions = JsonNode.Parse(File.ReadAllText(CorpusPath))!["sessions"]!.AsObject();
        var checked_ = 0;

        foreach (var (name, events) in sessions)
        {
            foreach (var evt in events!.AsArray())
            {
                var json = evt!.AsObject();
                if (json["kind"]!.GetValue<string>() != "message") continue;

                var fromTheFrame = MessageSetCodecs.ToJSON(
                                       Convert.FromHexString(json["exi"]!.GetValue<string>()),
                                       json["payloadType"]!.GetValue<string>(),
                                       json["messageName"]!.GetValue<string>());

                Assert.That(fromTheFrame.ToJsonString(), Is.EqualTo(json["json"]!.ToJsonString()),
                            $"{name}/{json["seq"]}: the event's JSON-LD is not what its own frame decodes to");
                checked_++;
            }
        }

        Assert.That(checked_, Is.GreaterThan(100), $"only {checked_} messages were checked");
    }


    /// <summary>
    /// The name in the document is the name the recorder gave.
    /// </summary>
    /// <remarks>
    /// <para>
    /// Two independent derivations of one value, required to agree. The recorder reads the decoded
    /// object's .NET type name; <see cref="MessageSetCodecs.MessageName"/> reads <c>@type</c> out of
    /// the JSON-LD. They agree because the emitter writes the type name as <c>@type</c> — but that is
    /// a fact about the emitter, not an identity, and it is the only reason a live session can name a
    /// message without reflecting over a type in three languages that name types three different
    /// ways.
    /// </para>
    /// <para>
    /// So it is checked here, over every recorded message: SAP, all of ISO 15118-2 wrapped in
    /// <c>V2G_Message</c>, and the -20 sets that are not.
    /// </para>
    /// </remarks>
    [Test]
    public void TheNameInTheDocumentIsTheNameTheRecorderGave()
    {

        var sessions = JsonNode.Parse(File.ReadAllText(CorpusPath))!["sessions"]!.AsObject();
        var checked_ = 0;

        foreach (var (name, events) in sessions)
        {
            foreach (var evt in events!.AsArray())
            {
                var json = evt!.AsObject();
                if (json["kind"]!.GetValue<string>() != "message") continue;

                Assert.That(MessageSetCodecs.MessageName(json["json"]!.AsObject()),
                            Is.EqualTo(json["messageName"]!.GetValue<string>()),
                            $"{name}/{json["seq"]}");
                checked_++;
            }
        }

        Assert.That(checked_, Is.GreaterThan(100), $"only {checked_} messages were checked");
    }


    /// <summary>
    /// The stream is a record, never a channel: no event asks the far side to do anything.
    /// </summary>
    /// <remarks>
    /// This is what keeps it safe to hand to a WebView. Asserted on the kinds rather than trusted,
    /// because the cost of adding a command-shaped event later is that nobody notices it was a
    /// different kind of thing.
    /// </remarks>
    [Test]
    public void EveryEventKindIsAnObservationRatherThanACommand()
    {

        var sessions = JsonNode.Parse(File.ReadAllText(CorpusPath))!["sessions"]!.AsObject();

        var kinds = sessions.SelectMany(s => s.Value!.AsArray())
                            .Select(e => e!["kind"]!.GetValue<string>())
                            .Distinct()
                            .OrderBy(k => k)
                            .ToList();

        Assert.That(kinds, Is.EquivalentTo(new[] { "message", "sessionFinished", "sessionStarted" }),
                    "a new event kind appeared: " + string.Join(", ", kinds));
    }


    /// <summary>
    /// A frame that cannot be read becomes an error event carrying the frame — not an exception, and
    /// not a silently dropped event.
    /// </summary>
    [Test]
    public void AnUnreadableFrameBecomesAnErrorThatCarriesIt()
    {

        var trace = JsonNode.Parse("""
            {
              "name": "broken", "protocol": "iso15118-2", "mode": "ac",
              "exchanges": [
                { "index": 0,
                  "request":  { "payloadType": "0x8001", "message": "SessionSetupReq", "frame": "01fe800100000002ffff" },
                  "response": null }
              ]
            }
            """)!;

        var events = new SessionEventStream(new SteppingClock().Read).Replay(trace).ToList();
        var error  = events.OfType<BridgeEvent.Error>().Single();

        Assert.Multiple(() => {
            Assert.That(error.Exi, Is.EqualTo("01fe800100000002ffff"), "the frame has to travel with the error");
            Assert.That(error.Detail, Does.Contain("SessionSetupReq"));
            Assert.That(((BridgeEvent.SessionFinished) events[^1]).Outcome, Is.EqualTo("failed"));
        });
    }


    /// <summary>Timings are monotonic and relative to the session's start.</summary>
    [Test]
    public void TimingsNeverGoBackwards()
    {

        var sessions = JsonNode.Parse(File.ReadAllText(CorpusPath))!["sessions"]!.AsObject();

        foreach (var (name, events) in sessions)
        {
            var previous = -1L;
            foreach (var evt in events!.AsArray())
            {
                var at = evt!["atMillis"]!.GetValue<long>();
                Assert.That(at, Is.GreaterThanOrEqualTo(previous), $"{name}: time went backwards");
                previous = at;
            }
        }
    }

}
