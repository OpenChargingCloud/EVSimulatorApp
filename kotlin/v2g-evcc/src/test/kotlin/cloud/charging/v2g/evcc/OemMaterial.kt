package cloud.charging.v2g.evcc

import com.google.gson.JsonObject
import com.google.gson.JsonParser
import java.io.File
import java.math.BigInteger
import java.security.AlgorithmParameters
import java.security.KeyFactory
import java.security.PrivateKey
import java.security.spec.ECGenParameterSpec
import java.security.spec.ECParameterSpec
import java.security.spec.ECPrivateKeySpec

import cloud.charging.v2g.keystore.InMemoryP256Signer
import cloud.charging.v2g.keystore.InMemoryP521Signer

/**
 * The fixed factory identities a recorded provisioning session asks with — [PncMaterial]'s
 * counterpart for the exchange that happens *before* a car has a contract, read out of the same
 * directory and generated by the same suite.
 *
 * Three of them, because -2 agrees on secp256r1 and -20 on secp521r1, and because an update presents
 * the expiring contract rather than an OEM certificate. See `OemMaterial.cs` for the whole argument.
 */
internal object OemMaterial {

    private val material: JsonObject by lazy {
        var dir = File(".").absoluteFile
        while (!File(dir, "EVSimulatorApp.slnx").isFile)
            dir = dir.parentFile ?: error("repository root not found")

        val file = File(dir, "vectors/Session.oem-material.json")
        require(file.isFile) { "OEM material not found at $file" }
        JsonParser.parseString(file.readText()).asJsonObject
    }

    /** The car that has never had a contract, asking for its first. */
    val iso2Install: Iso2CertInstallOptions by lazy { iso2("iso2Oem", Iso2CertificateAction.Install) }

    /** The car whose contract is running out, asking for the next. */
    val iso2Update: Iso2CertInstallOptions by lazy { iso2("iso2Expiring", Iso2CertificateAction.Update) }

    /** The -20 errand, which needs the P-521 identity: a P-256 provisioning certificate has no shared
     *  curve with the station's secp521r1 agreement and could not open the answer. */
    val iso20Install: CertInstallEvccOptions by lazy {

        val entry = material.getAsJsonObject("iso20Oem")
        val key   = privateKey(entry, "secp521r1")

        CertInstallEvccOptions(
            oemCertificate     = hex(entry.get("certificate").asString),
            oemSubCertificates = emptyList(),
            oemSignKey         = InMemoryP521Signer(key, publicKeyDer = ByteArray(0)),
            // The same key object, twice: signing may be delegated to hardware that never reveals the
            // scalar, but an ECDH agreement needs the private key itself.
            oemKeyAgreement    = key)
    }

    private fun iso2(name: String, action: Iso2CertificateAction): Iso2CertInstallOptions {

        val entry = material.getAsJsonObject(name)
        val key   = privateKey(entry, "secp256r1")

        return Iso2CertInstallOptions(
            certificate  = hex(entry.get("certificate").asString),
            signKey      = InMemoryP256Signer(key, publicKeyDer = ByteArray(0)),
            keyAgreement = key,
            action       = action,
            emaid        = entry.get("emaid")?.takeIf { !it.isJsonNull }?.asString)
    }

    private fun privateKey(entry: JsonObject, curveName: String): PrivateKey {
        val parameters = AlgorithmParameters.getInstance("EC").apply {
            init(ECGenParameterSpec(curveName))
        }.getParameterSpec(ECParameterSpec::class.java)

        return KeyFactory.getInstance("EC").generatePrivate(
            ECPrivateKeySpec(BigInteger(1, hex(entry.get("privateKeyD").asString)), parameters))
    }

    private fun hex(s: String) = ByteArray(s.length / 2) {
        ((s[it * 2].digitToInt(16) shl 4) or s[it * 2 + 1].digitToInt(16)).toByte()
    }
}
